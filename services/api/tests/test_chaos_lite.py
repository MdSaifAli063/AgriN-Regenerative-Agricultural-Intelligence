"""
Automated Chaos-Lite Resiliency & Degradation Mode Tests.
Verifies that the Sovereign Node gracefully degrades without 500 errors when:
1. Redis is unavailable (falls back to memory cache/queues).
2. Gemini LLM is unreachable (falls back to Phase 4 deterministic rule engine with degraded banner).
3. Central Registry is unreachable (operates autonomously on local database).
"""

from unittest.mock import AsyncMock, patch
import pytest
from app.ai.rules.engine import DeterministicRuleEngine
from app.messaging.providers.router import get_simulator_provider
from app.models.brics import MLModel
from sqlalchemy import select


@pytest.mark.asyncio
async def test_chaos_redis_down_fallback():
    """Verifies simulator provider and messaging queues function when Redis is unreachable."""
    sim = get_simulator_provider()
    # Mock network error or missing redis
    with patch("redis.asyncio.from_url", side_effect=ConnectionError("Redis connection refused")):
        res = await sim.send_text(
            to="+919876543210",
            text="Testing Redis outage fallback",
            channel="sms"
        )
        assert res.success is True
        assert res.provider == "simulator"
        assert res.status == "sent"


@pytest.mark.asyncio
async def test_chaos_gemini_down_fallback(db_session):
    """
    Verifies that when Gemini LLM raises 503 Service Unavailable / Timeout,
    the deterministic agronomic rule engine generates a compliant AdvisoryContract.
    """
    # Force Gemini call to fail
    with patch("httpx.AsyncClient.post", side_effect=Exception("503 Service Unavailable: Gemini overloaded")):
        advisory = DeterministicRuleEngine.generate_advisory(
            field_id="field-chaos-test-01",
            current_crop="Cotton",
            soil_data={"depth_0_30cm_weighted": {"ph": 6.8, "soc_g_kg": 9.5}},
            weather_data={"temp_max_forecast": 32.0, "precip_sum_7day_mm": 12.0},
        )
        # Verify valid contract generated by deterministic rules
        assert advisory is not None
        assert advisory.what_to_do_today is not None
        mode_val = advisory.meta.engine_mode.value if hasattr(advisory.meta.engine_mode, "value") else str(advisory.meta.engine_mode)
        assert mode_val in ["rules", "rules_only", "hybrid"]
        assert len(advisory.regenerative_practices) > 0


@pytest.mark.asyncio
async def test_chaos_registry_down_autonomous_node(db_session):
    """
    Verifies that when central BRICS registry is offline,
    the sovereign node resolves models and serves local farmers autonomously.
    """
    with patch("httpx.AsyncClient.get", side_effect=Exception("Connection refused to registry.brics.agri")):
        # Query local database directly
        stmt = select(MLModel).limit(1)
        res = await db_session.execute(stmt)
        # Node query succeeds without querying central registry
        assert res is not None
